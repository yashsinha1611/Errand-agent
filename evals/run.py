"""Run every scenario, check every invariant, and write the eval table.

    python -m evals.run            # writes reports/eval_table.md and reports/eval_results.json
"""
from __future__ import annotations

import datetime
import json
import os
import shutil
import subprocess
import sys
import traceback

from errand.mock.provider import MockConfig

from .harness import Harness
from .invariants import check_all
from .scenarios import SCENARIOS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def run_one(sc) -> dict:
    h = Harness(sc.id, mock=MockConfig(mode="calm", **sc.mock), caps=sc.caps or None,
                model=sc.model() if sc.model else None)
    error = None
    try:
        actual = sc.run(h)
    except Exception as exc:  # noqa: BLE001
        actual = f"crashed: {type(exc).__name__}: {exc}"
        error = traceback.format_exc()
    invariants = check_all(h)
    failed_checks = [c.desc for c in h.checks if not c.ok]
    failed_inv = [f"{name.split(' ')[0]}: {detail}" for name, ok, detail in invariants if not ok]
    passed = error is None and not failed_checks and not failed_inv
    if sc.id == "S10":
        os.makedirs(os.path.join(ROOT, "docs", "traces"), exist_ok=True)
        shutil.copy(h.trace_file(), os.path.join(ROOT, "docs", "traces", "timeout_after_success.jsonl"))
    notes = "; ".join(failed_checks + failed_inv) or f"{len(h.checks)} checks, 10 invariants"
    h.cleanup()
    return {"id": sc.id, "title": sc.title, "covers": sc.covers, "expected": sc.expected, "actual": actual,
            "passed": passed, "notes": notes, "error": error}


def git_sha() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, timeout=5).stdout.strip() or "uncommitted"
    except Exception:  # noqa: BLE001
        return "unknown"


def write_reports(results: list[dict]) -> str:
    os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
    passed = sum(r["passed"] for r in results)
    stamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        "# Eval results",
        "",
        f"{passed}/{len(results)} scenarios passed · git {git_sha()} · {stamp} · offline rule model · mock seed 7",
        "",
        "Generated by `python -m evals.run`. Do not edit by hand. Every scenario also runs the 10 global "
        "invariants (see evals/invariants.py).",
        "",
        "| Scenario | Expected | Actual | Result | Notes |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in sorted(results, key=lambda r: int(r["id"][1:])):
        cell = lambda s: str(s).replace("|", "\\|").replace("\n", " ")  # noqa: E731
        lines.append(f"| {r['id']} {cell(r['title'])} | {cell(r['expected'])} | {cell(r['actual'])} | "
                     f"{'pass' if r['passed'] else '**FAIL**'} | {cell(r['notes'])} |")
    md = "\n".join(lines) + "\n"
    with open(os.path.join(ROOT, "reports", "eval_table.md"), "w", encoding="utf-8") as fh:
        fh.write(md)
    with open(os.path.join(ROOT, "reports", "eval_results.json"), "w", encoding="utf-8") as fh:
        json.dump({"passed": passed, "total": len(results), "git": git_sha(), "results": results}, fh, indent=1)
    return md


def main() -> int:
    results = [run_one(sc) for sc in SCENARIOS]
    write_reports(results)
    for r in sorted(results, key=lambda r: int(r["id"][1:])):
        print(f"{'PASS' if r['passed'] else 'FAIL'}  {r['id']:4} {r['title'][:60]:60}  {r['actual'][:60]}")
        if not r["passed"]:
            print(f"      notes: {r['notes'][:300]}")
            if r["error"]:
                print("      " + r["error"].strip().splitlines()[-1])
    passed = sum(r["passed"] for r in results)
    print(f"\n{passed}/{len(results)} scenarios passed. Table: reports/eval_table.md")
    return 0 if passed == len(results) else 1


if __name__ == "__main__":
    sys.exit(main())
